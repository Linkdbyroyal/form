import Link from "next/link";
import { notFound } from "next/navigation";
import { clientNav, Shell } from "@/components/shell";
import { Badge, Card, Empty, Stat, Status } from "@/components/ui";
import { Notice, PageHeader, ShortId, smallPrimaryClass } from "@/components/agent-ui";
import { ReviewStatusBadge } from "@/components/xray-ui";
import { DashboardRenderer } from "@/components/dashboard/dashboard-renderer";
import { getTenantHeader } from "@/lib/client/queries";
import { getDashboardPage } from "@/lib/client/xray-queries";
import { regenerateDashboardAction } from "@/lib/client/action-actions";
import { deriveKpiState } from "@/lib/client/kpi-state";
import { firstParam, fmtDate } from "@/lib/format";
import { requireTenantContext } from "@/lib/request-context";

export const dynamic = "force-dynamic";

export default async function CeoDashboardPage({ params, searchParams }: { params: Promise<{ slug: string }>; searchParams: Promise<Record<string, string | string[] | undefined>> }) {
  const { slug } = await params;
  const sp = await searchParams;
  const access = await requireTenantContext(slug);
  if (!access) notFound();
  const [tenant, page] = await Promise.all([getTenantHeader(access.ctx), getDashboardPage(access.ctx, slug)]);
  if (!tenant) notFound();
  const isAdmin = !access.viaGrant && access.ctx.roles.includes("client_admin");
  const returnTo = `/c/${slug}/dashboard`;
  const states = page.data.kpis.map((k) => deriveKpiState(k).state);
  const count = (s: string) => states.filter((x) => x === s).length;
  const d = page.dashboard;
  return (
    <Shell title={tenant.name} subtitle="Client workspace" nav={clientNav(slug)}>
      <div className="space-y-6">
        <PageHeader title="CEO Dashboard">
          Rendered from the current <code>DashboardSpecification</code> produced by the CEO Intelligence agent, through a fixed whitelist of nine widget types. Every number links to its KPI lineage (source, formula, owner, observations, audit). Missing or stale data is shown as a state, never as a number. <Status state="implemented" />
        </PageHeader>
        <Notice ok={firstParam(sp.ok)} error={firstParam(sp.error)} />

        <Card title="Specification">
          {!d ? (
            <Empty>
              <div className="space-y-2">
                <p>No CEO dashboard has been published for this workspace yet.</p>
                <p className="text-xs">The CEO Intelligence agent defines the KPI registry (each KPI with source system, field and formula) and publishes the dashboard specification; the worker validates it against the contract before it is stored.</p>
                {isAdmin ? (
                  <form action={regenerateDashboardAction} className="pt-2">
                    <input type="hidden" name="slug" value={slug} />
                    <input type="hidden" name="returnTo" value={returnTo} />
                    <button type="submit" className={smallPrimaryClass} disabled={!page.ceoAgent}>Generate dashboard now</button>
                    {!page.ceoAgent ? <div className="mt-1 text-xs text-warning">No CEO Intelligence agent instance exists for this workspace.</div> : null}
                  </form>
                ) : (
                  <p className="text-xs">A client admin can request a run from this page.</p>
                )}
              </div>
            </Empty>
          ) : (
            <div className="flex flex-wrap items-start justify-between gap-4 text-sm">
              <dl className="grid grid-cols-[auto_1fr] gap-x-4 gap-y-1">
                <dt className="text-faint">Title</dt><dd className="font-medium">{d.title}</dd>
                <dt className="text-faint">Version</dt><dd>v{d.version} <span className="text-faint">of {page.versions.length} stored</span></dd>
                <dt className="text-faint">Generated by</dt><dd>{d.generatedBy ?? "unknown agent"}{d.runId ? <span className="text-faint"> · run <ShortId id={d.runId} /></span> : null}</dd>
                <dt className="text-faint">Published</dt><dd>{fmtDate(d.createdAt)}</dd>
                <dt className="text-faint">Review status</dt><dd><ReviewStatusBadge value={d.reviewStatus} /></dd>
              </dl>
              <div className="flex flex-col items-end gap-2">
                <Link href={`/c/${slug}/briefing`} className="text-xs underline">Executive briefing</Link>
                {isAdmin ? (
                  <form action={regenerateDashboardAction}>
                    <input type="hidden" name="slug" value={slug} />
                    <input type="hidden" name="returnTo" value={returnTo} />
                    <button type="submit" className={smallPrimaryClass} disabled={!page.ceoAgent}>Regenerate</button>
                  </form>
                ) : null}
                {page.ceoAgent ? <span className="text-[11px] text-faint">{page.ceoAgent.name}: {page.ceoAgent.state}</span> : null}
              </div>
            </div>
          )}
        </Card>

        <div className="grid gap-4 md:grid-cols-4">
          <Stat label="KPIs in registry" value={page.data.kpis.length} hint="each with source system, field and formula" />
          <Stat label="OK" value={count("ok")} hint="latest observation carries a value" />
          <Stat label="Missing data" value={count("missing")} hint="source not connected or no observation" />
          <Stat label="Stale or error" value={count("stale") + count("error")} hint="shown as a state, never a number" />
        </div>

        {d ? <DashboardRenderer specification={d.specification} data={page.data} /> : null}

        <Card title="Implementation status">
          <ul className="space-y-1 text-sm">
            <li><Status state="implemented" /> Specification validated against the contract on render; unknown widget types are refused (M3-03)</li>
            <li><Status state="implemented" /> Nine widget types: kpi_tile, trend_line, bar, table, action_list, briefing, risk_list, data_gap_list, text_note; charts on Recharts with accessibilityLayer</li>
            <li><Status state="implemented" /> KPI lineage page per KPI; regenerate through a CEO Intelligence run (client_admin)</li>
            <li><Status state={page.data.briefing?.simulated === false ? "implemented" : "simulated"} /> Agent output: {page.data.briefing?.simulated === false ? "produced by a live model run" : "produced by the simulated runtime (no ANTHROPIC_API_KEY on the worker)"}</li>
            <li><Status state="not_connected" /> External KPI sources (Rentman, QuickBooks Online): observations stay <Badge tone="warning">Missing data</Badge> until a read-only connection with consent exists (M5)</li>
            <li><Status state="planned" /> Visual regression snapshots per widget state (Playwright)</li>
          </ul>
        </Card>
      </div>
    </Shell>
  );
}
